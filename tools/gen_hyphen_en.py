"""从 TeX en-US 断词模式生成 C 表。

Generate the C table from the TeX en-US hyphenation patterns.

用法 / Usage:
    python3 tools/gen_hyphen_en.py <hyph-en-us.tex> > main/book/hyphen_en.h

来源模式为 Knuth/Liang 的 en-US 集合（tex-hyphen 仓库维护，可自由使用）。
本文件是生成器；产物 hyphen_en.h 是生成表，勿手改。
The source patterns are the Knuth/Liang en-US set (maintained in the tex-hyphen
repository, freely usable). This file is the generator; hyphen_en.h is a
generated table — do not hand-edit.
"""
import re
import sys


def parse(path):
    text = open(path, encoding="utf-8").read()
    patterns = []
    for line in text.splitlines():
        line = line.split("%", 1)[0].strip()
        if not line or line.startswith("\\"):
            continue
        for token in line.split():
            if re.fullmatch(r"[.a-z0-9']+", token):
                patterns.append(token)
    return patterns


def encode(token):
    letters = []
    digits = []
    digit = "0"
    for ch in token:
        if ch.isdigit():
            digit = ch
        else:
            letters.append(ch)
            digits.append(digit)
            digit = "0"
    digits.append(digit)
    return "".join(letters), bytes(int(d) for d in digits)


def main():
    patterns = parse(sys.argv[1])
    encoded = sorted(encode(t) for t in patterns)
    # 按前两个字符分桶：匹配时只扫同桶。/ Bucket by the first two characters.
    buckets = {}
    for letters, digits in encoded:
        key = (letters[:2] + "..")[:2]
        buckets.setdefault(key, []).append((letters, digits))

    print("/* SPDX-FileCopyrightText: 2026 mindreset")
    print(" * SPDX-License-Identifier: Apache-2.0")
    print(" *")
    print(" * 中文：en-US TeX 断词模式表（Knuth/Liang，tex-hyphen 维护，可自由使用）。")
    print(" * 由 tools/gen_hyphen_en.py 生成，勿手改。")
    print(" * English: en-US TeX hyphenation patterns (Knuth/Liang, maintained by")
    print(" * tex-hyphen, freely usable). Generated by tools/gen_hyphen_en.py — do not edit.")
    print(" */")
    print("#pragma once")
    print("#include <stdint.h>")
    print("")
    print("#define HYPHEN_EN_PATTERN_COUNT %d" % len(encoded))
    pool = []
    entries = []
    for letters, digits in encoded:
        pool.append(letters)
        entries.append((len(pool) - 1, digits))
    pool_var = "static const char k_hyphen_pool[] =\n" + "\n".join(
        '    "%s\\0"' % p.replace("\\", "\\\\").replace('"', '\\"') for p in pool)
    # 结尾补一个空串终止，方便只存偏移。/ A terminating empty string keeps offsets-only entries simple.
    print(pool_var + '    ;')
    letters_ofs = []
    digit_data = bytearray()
    digit_ofs = []
    for index, digits in entries:
        letters_ofs.append(sum(len(pool[i]) + 1 for i in range(index)))
        digit_ofs.append(len(digit_data))
        digit_data.extend(digits)
    print("static const uint16_t k_hyphen_letters[%d] = {%s};" % (
        len(letters_ofs), ",".join(str(o) for o in letters_ofs)))
    print("static const uint16_t k_hyphen_digits[%d] = {%s};" % (
        len(digit_ofs), ",".join(str(o) for o in digit_ofs)))
    print("static const uint8_t k_hyphen_digit_data[] = {%s};" % (
        ",".join(str(b) for b in digit_data)))
    keys = sorted(buckets.keys())
    # 键里 '.' 提升为 '{'，保持 '.'<'a' 的单次序比较。/ Promote '.' to '{' in keys,
    # keeping one comparison order with '.' below 'a'.
    promoted = "".join('{' if c == '.' else c for c in "".join(keys))
    print("static const char k_hyphen_keys[] = \"%s\";" % promoted)
    starts = []
    key_index = {k: i for i, k in enumerate(keys)}
    cursor = 0
    per_bucket = {}
    for letters, digits in encoded:
        key = (letters[:2] + "..")[:2]
        per_bucket.setdefault(key, []).append(cursor)
        cursor += 1
    flat = []
    ranges = []
    for key in keys:
        ranges.append((len(flat), len(per_bucket[key])))
        flat.extend(per_bucket[key])
    print("static const uint16_t k_hyphen_flat[%d] = {%s};" % (len(flat), ",".join(str(i) for i in flat)))
    print("static const uint16_t k_hyphen_bucket_range[%d] = {%s};" % (
        len(keys) * 2, ",".join("%d,%d" % r for r in ranges)))
    # 桶键字符表与范围一一对应；键为两个字符（点号补齐）。
    # Bucket keys are two characters each (dot-padded), parallel to the ranges.
    print("#define HYPHEN_EN_BUCKET_COUNT %d" % len(keys))


if __name__ == "__main__":
    main()
